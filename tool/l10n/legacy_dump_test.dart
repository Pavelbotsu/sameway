    final out = <String, Map<String, String>>{};
    for (final code in ['en', 'uk', 'pl']) {
      final l = AppLocalizations(Locale(code));
      final all = {..._getters(), ..._methods()};
      all.forEach((key, f) {
        var v = f(l);
        _sentinels.forEach((k, s) => v = v.replaceAll(k, s));
        (out[key] ??= {})[code] = v;
      });
    }
    File('build/legacy_dump.json')
      ..createSync(recursive: true)
      ..writeAsStringSync(const JsonEncoder.withIndent('  ').convert(out));
  });
}
