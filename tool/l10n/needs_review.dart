// Lists every uk/pl string marked "x-needs-review" as Markdown (decision 28:
// the product owner reviews UK and PL). Writes ../design-pack/l10n/needs_review.md,
// which lives in the design pack next to copy_deck.csv; the PR links to it.
//
//   dart run tool/l10n/needs_review.dart            # write the file
//   dart run tool/l10n/needs_review.dart --stdout   # print instead
//   dart run tool/l10n/needs_review.dart uk         # one language
//   dart run tool/l10n/needs_review.dart --count    # totals only
import 'dart:convert';
import 'dart:io';

const _out = '../design-pack/l10n/needs_review.md';

Map<String, dynamic> _arb(String code) =>
    jsonDecode(File('lib/l10n/app_$code.arb').readAsStringSync())
        as Map<String, dynamic>;

String _cell(String s) => s.replaceAll('|', r'\|').replaceAll('\n', '<br>');

void main(List<String> args) {
  final countOnly = args.contains('--count');
  final toStdout = args.contains('--stdout');
  final langs = args.where((a) => !a.startsWith('--')).toList();
  final en = _arb('en');
  final md = StringBuffer()
    ..writeln('# Strings to review (UK, PL)')
    ..writeln()
    ..writeln('Written or changed by the developer, not taken as-is from the '
        'copy deck. Marked `"x-needs-review": true` in '
        '`sameway/lib/l10n/app_uk.arb` / `app_pl.arb`. Generated by '
        '`dart run tool/l10n/needs_review.dart` (in `sameway/`); don’t edit '
        'by hand. When a string is approved, remove its marker and rerun.')
    ..writeln();
  for (final code in langs.isEmpty ? ['uk', 'pl'] : langs) {
    final arb = _arb(code);
    final keys = [
      for (final k in arb.keys)
        if (k.startsWith('@') &&
            !k.startsWith('@@') &&
            (arb[k] as Map)['x-needs-review'] == true)
          k.substring(1),
    ];
    if (countOnly) {
      stdout.writeln('$code: ${keys.length}');
      continue;
    }
    md
      ..writeln('## ${code.toUpperCase()}: ${keys.length} strings')
      ..writeln()
      ..writeln('| Key | English | ${code.toUpperCase()} |')
      ..writeln('|---|---|---|');
    for (final k in keys) {
      md.writeln('| `$k` | ${_cell('${en[k]}')} | ${_cell('${arb[k]}')} |');
    }
    md.writeln();
  }
  if (countOnly) return;
  if (toStdout) {
    stdout.write(md);
    return;
  }
  final file = File(_out);
  if (!file.parent.existsSync()) {
    stderr.writeln('${file.parent.path} not found: check out design-pack next '
        'to sameway, or use --stdout');
    exit(1);
  }
  file.writeAsStringSync(md.toString());
  stdout.writeln('wrote ${file.path}');
}
